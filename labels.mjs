// Writes LABELS.md: what the user reads for each command, taken from the 2.1 descriptor.
import fs from 'node:fs';
const d = JSON.parse(fs.readFileSync('descriptors/universal-router-2.1.json'));
const COMMANDS = { '0x00': 'V3_SWAP_EXACT_IN', '0x01': 'V3_SWAP_EXACT_OUT', '0x02': 'PERMIT2_TRANSFER_FROM', '0x03': 'PERMIT2_PERMIT_BATCH', '0x04': 'SWEEP', '0x05': 'TRANSFER', '0x06': 'PAY_PORTION', '0x07': 'PAY_PORTION_FULL_PRECISION', '0x08': 'V2_SWAP_EXACT_IN', '0x09': 'V2_SWAP_EXACT_OUT', '0x0a': 'PERMIT2_PERMIT', '0x0b': 'WRAP_ETH', '0x0c': 'UNWRAP_WETH', '0x0d': 'PERMIT2_TRANSFER_FROM_BATCH', '0x0e': 'BALANCE_CHECK_ERC20', '0x10': 'V4_SWAP', '0x11': 'V3_POSITION_MANAGER_PERMIT', '0x12': 'V3_POSITION_MANAGER_CALL', '0x14': 'V4_POSITION_MANAGER_CALL', '0x13': 'V4_INITIALIZE_POOL', '0x21': 'EXECUTE_SUB_PLAN', '0x40': 'ACROSS_V4_DEPOSIT_V3' };
const ACTIONS = { '0x06': 'SWAP_EXACT_IN_SINGLE', '0x07': 'SWAP_EXACT_IN', '0x08': 'SWAP_EXACT_OUT_SINGLE', '0x09': 'SWAP_EXACT_OUT', '0x0b': 'SETTLE', '0x0c': 'SETTLE_ALL', '0x0e': 'TAKE', '0x0f': 'TAKE_ALL', '0x10': 'TAKE_PORTION' };

function field(f) {
  if (f.interaction) return 'the commands of the sub-plan, as below';
  if (f.format === 'customEncoding' || f.visible === 'never' || (f.switch && f.path.endsWith('.[]'))) return null;
  const notes = [];
  const choices = Object.entries(f.switch?.cases ?? {});
  const p = f.params ?? choices.map(([, c]) => c).find((c) => c?.params)?.params ?? {};
  if (p.threshold) notes.push(`"${p.message}" for ${p.threshold.length > 20 ? (p.threshold.startsWith('0x8') ? '2^255' : 'the maximum') : p.threshold}`);
  if (f.switch) {
    const by = f.switch.expression.path.split('.').pop();
    const refused = choices.find(([, c]) => c === 'reject');
    if (refused) notes.push(`refused when \`${by}\` is ${refused[0] === '0x00' ? 'zero' : refused[0]}`);
    else notes.push(by === 'useNative' ? 'ETH when `useNative`' : `token chosen by \`${by}\``);
  }
  if (p.chainIdPath) notes.push('token looked up on the destination chain');
  if (f.visible?.ifNotIn) notes.push(`hidden when ${JSON.stringify(f.visible.ifNotIn[0]).replace('"0x0000000000000000000000000000000000000000"', 'zero').replace('"0x"', 'empty')}`);
  if (p.senderAddress) notes.push('`0x…01` shown as the sender');
  return `**${f.label}**${notes.length ? ` (${notes.join(', ')})` : ''}`;
}
const row = (code, name, spec) => `| \`${code}\` ${name} | ${spec.intent} | ${spec.fields.map(field).filter(Boolean).join(' · ')} |`;

const top = d.display.formats['execute(bytes commands,bytes[] inputs,uint256 deadline)'];
const cases = top.fields.find((f) => f.switch).switch.cases;
const out = ['# What the user reads', '', 'Generated by `labels.mjs` from `descriptors/universal-router-2.1.json`. Router 2.0 has the same labels, without `0x07` and `0x40`. The routers before 2.0 have those of 2.0 that are not about v4 or positions; the first one also lacks `0x0e` and `0x21`.', '',
  `Every call starts with **${top.intent}**, then **Native Amount** when ETH is sent, one group per command, and **Valid Until**.`, '',
  '## Commands', '', '| Command | Group | Fields |', '|---|---|---|'];
let v4;
for (const [code, c] of Object.entries(cases)) {
  if (code === '$default') continue;
  if (c.format === 'calldata') {
    const which = c.params.callee.includes('v3') ? 'v3' : 'v4';
    out.push(`| \`${code}\` ${COMMANDS[code]} | that of the call | a whole call to the ${which} position manager, shown with that contract's own descriptor |`);
    continue;
  }
  const spec = Object.values(c)[0];
  if (code === '0x10') { v4 = spec.fields.find((f) => f.switch).switch.cases; out.push(`| \`0x10\` V4_SWAP | ${spec.intent} | one group per action, see below |`); continue; }
  out.push(row(code, COMMANDS[code], spec));
}
out.push('', 'Any other command: the transaction is refused, not shown in part.', '', '## Actions inside `V4_SWAP`', '', '| Action | Group | Fields |', '|---|---|---|');
for (const [code, c] of Object.entries(v4)) if (code !== '$default') out.push(row(code, ACTIONS[code], Object.values(c)[0]));
out.push('', 'Any other action: refused.', '');

// The v4 position manager has a descriptor of its own, used for command 0x14 and for direct calls.
const pm = JSON.parse(fs.readFileSync('descriptors/v4-position-manager.json'));
const PM_ACTIONS = { '0x00': 'INCREASE_LIQUIDITY', '0x01': 'DECREASE_LIQUIDITY', '0x02': 'MINT_POSITION', '0x03': 'BURN_POSITION', '0x04': 'INCREASE_LIQUIDITY_FROM_DELTAS', '0x05': 'MINT_POSITION_FROM_DELTAS', '0x0b': 'SETTLE', '0x0d': 'SETTLE_PAIR', '0x0e': 'TAKE', '0x11': 'TAKE_PAIR', '0x12': 'CLOSE_CURRENCY', '0x13': 'CLEAR_OR_TAKE', '0x14': 'SWEEP', '0x15': 'WRAP', '0x16': 'UNWRAP' };
const pmTop = Object.values(pm.display.formats)[0];
out.push('## The v4 position manager', '',
  'Generated from `descriptors/v4-position-manager.json`, for `modifyLiquidities`: called directly, or by the router for command `0x14`.',
  `A call starts with **${pmTop.intent}**, then one group per action, and **Valid Until**. Here \`0x…01\` is the caller, which is the router when the call comes through it.`, '',
  '| Action | Group | Fields |', '|---|---|---|');
for (const [code, c] of Object.entries(pmTop.fields.find((f) => f.switch).switch.cases)) if (code !== '$default') out.push(row(code, PM_ACTIONS[code], Object.values(c)[0]));
out.push('', 'Any other action: refused.', '',
  '## Choices worth a second opinion', '',
  '- **Minimum Output** on a swap, **Minimum to Receive** only on a step that pays the user. A swap can pay the router first, with a fee taken after it.',
  '- **Collect at Least** for `SWEEP`, which sends whatever the router holds.',
  '- **Paid by you** is shown only when it is false, that is when the router spends what it already holds.',
  '- An amount of 0 in `SETTLE` and `TAKE` means everything that is open. It is hidden, since "0 USDC" reads as nothing.',
  '- A hook and its data are shown whenever the pool has one. The user cannot judge a hook, but should know there is one.',
  '- In an Across deposit, **Recipient on Destination** and **Refund Address** are shown as they are. The router does not map `0x…01` and `0x…02` there, so they are not "you" and "the router".',
  '- An Across deposit that names no output token is refused: the pool would pick one, and the wallet could not say which.',
  '- In the position manager, actions on an existing position name no pool, so their amounts are raw. A token named without an amount is a ticker, which the format cannot give for the native currency.',
  '- **Forfeit if at Most** for `CLEAR_OR_TAKE`: what the pool owes is given up when it is this amount or less.', '');
fs.writeFileSync('LABELS.md', out.join('\n'));
